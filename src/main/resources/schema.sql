CREATE SCHEMA IF NOT EXISTS GAME;

CREATE TABLE GAME.MATCH_RESULT (
    MATCH_RESULT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ATTACKER_ID BIGINT NOT NULL,
    DEFENDER_ID BIGINT NOT NULL,
    GAME_ID BIGINT NOT NULL,
    MATCH_DATETIME TIMESTAMP NOT NULL,
    JUDGE INTEGER NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    VERSION INTEGER NOT NULL,
    ATTACKER_DIRECTION INTEGER NOT NULL,
    DEFENDER_DIRECTION INTEGER NOT NULL
);
