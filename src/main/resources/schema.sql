CREATE SCHEMA IF NOT EXISTS GAME;

CREATE TABLE GAME.MATCH_RESULT (
    MATCH_RESULT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ATTACKER_ID BIGINT NOT NULL,
    DEFENDER_ID BIGINT NOT NULL,
    GAME_ID BIGINT NOT NULL,
    MATCH_DATETIME TIMESTAMP NOT NULL,
    JUDGE INTEGER NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    VERSION INTEGER NOT NULL,
    ATTACKER_DIRECTION INTEGER NOT NULL,
    DEFENDER_DIRECTION INTEGER NOT NULL
);

-- ユーザ ID 用のシーケンス
CREATE SEQUENCE seq_user_id START WITH 1;

-- ユーザ情報テーブル
CREATE TABLE IF NOT EXISTS user_information_tbl (
    user_id BIGINT GENERATED BY DEFAULT AS SEQUENCE seq_user_id PRIMARY KEY,
    user_name VARCHAR(100) NOT NULL UNIQUE,
    mail_address VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    status int NOT NULL,
    create_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    update_datetime TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL,
    version INT DEFAULT 1 NOT NULL
);

-- 履歴テーブル用シーケンス
CREATE SEQUENCE seq_history_id START WITH 1;

-- ゲームの種類マスタ
CREATE TABLE game_type_mst (
    game_type_id INT PRIMARY KEY,
    game_name VARCHAR(50) NOT NULL
