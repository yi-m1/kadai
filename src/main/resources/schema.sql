-- 履歴テーブル
CREATE TABLE result_history_tbl (
    history_id BIGINT GENERATED BY DEFAULT AS SEQUENCE seq_history_id PRIMARY KEY,
    user_id BIGINT NOT NULL,
    game_type_id INT NOT NULL,
    result_id INT NOT NULL,
    execute_datetime DATETIME NOT NULL,
    opponent BIGINT NOT NULL,
    user_choice VARCHAR(10),
    create_datetime DATETIME NOT NULL,
    update_datetime DATETIME NOT NULL,
    version INT NOT NULL,
    FOREIGN KEY (game_type_id, result_id)
        REFERENCES game_result_mst(game_type_id, result_id)
);

