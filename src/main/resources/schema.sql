-- ゲーム × 結果の組み合わせマスタ
CREATE TABLE game_result_mst (
    game_type_id INT NOT NULL,
    result_id INT NOT NULL,
    PRIMARY KEY (game_type_id, result_id),
    FOREIGN KEY (game_type_id) REFERENCES game_type_mst(game_type_id),
    FOREIGN KEY (result_id) REFERENCES result_mst(result_id)
);

